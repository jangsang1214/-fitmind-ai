'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const stripComments=value=>String(value).replace(/\/\*[\s\S]*?\*\//g,'').replace(/(^|\s)\/\/.*$/gm,'$1');
const version=read('07_config/version.js');
const css=read('03_styles/runtime/garang-founder-exact-v7.css');
const runtime=read('06_features/ui/runtime/garang-founder-exact-v7.js');
const anatomy=read('06_features/ui/runtime/garang-anatomy-exact-v2.js');
const workoutAsset=read('05_assets/workout-benchpress-v1.svg');
const executable=[css,runtime,anatomy].map(stripComments).join('\n');

assert.match(version,/garang-founder-exact-v7\.css/,'loader must load Founder Exact v7 stylesheet');
assert.match(version,/garang-founder-exact-v7\.js/,'loader must load Founder Exact v7 structural adapter');
assert.match(version,/garang-anatomy-exact-v2\.js/,'loader must load exact interactive anatomy');
assert.doesNotMatch(version,/garang-founder-target-v6\.(?:css|js)|garang-founder-target-v5\.(?:css|js)|garang-reference-ui-v2|garang-presentation-v4\.(?:css|js)/,'loader must not restore superseded visual layers');
assert.doesNotMatch(executable,/target-board|commercial-approved-v3|reference-board|\.jpg\b|\.jpeg\b|\.png\b/i,'exact presentation must not reference board screenshots or cropped concept photography');
assert.match(runtime,/workout-benchpress-v1\.svg/,'Workout hero must use a GARANG-owned original asset');
assert.match(workoutAsset,/GARANG bench press training visual/,'Workout hero asset must be original GARANG SVG');
assert.doesNotMatch(runtime,/cloneNode\s*\(/,'presentation must move canonical action/state owners instead of cloning them');
assert.doesNotMatch(runtime,/replaceChildren\s*\(/,'presentation must not replace canonical interactive owners');
assert.match(runtime,/q\(m,'#garangTodayFlow'\)/,'Today must reuse canonical Today owner');
assert.match(runtime,/document\.getElementById\('workoutExecutionRest'\)/,'Rest must reuse canonical timer owner');
assert.match(runtime,/q\(m,'\.meal-scan-card'\)/,'Nutrition must reuse canonical Meal Scan owner');
assert.match(runtime,/document\.getElementById\('finishWorkoutSession'\)/,'Record must reuse canonical session finish action');
assert.match(anatomy,/data-muscle/,'Body visible geometry must expose muscle hit geometry on the same SVG');
assert.match(anatomy,/canonical\.click\(\)/,'new visible muscle geometry must relay selection to an existing canonical muscle owner when present');
assert.match(anatomy,/garang:body-muscle-selected/,'anatomy must emit a semantic selection event');
console.log('Founder Exact v7 clean rebuild + full no-crop contract: PASS');
