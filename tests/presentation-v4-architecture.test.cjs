'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const stripComments=value=>String(value).replace(/\/\*[\s\S]*?\*\//g,'').replace(/(^|\s)\/\/.*$/gm,'$1');
const version=read('07_config/version.js');
const foundation=read('03_styles/runtime/garang-founder-v8-foundation.css');
const screens=read('03_styles/runtime/garang-founder-v8-screens.css');
const runtime=read('06_features/ui/runtime/garang-founder-v8.js');
const bodyReadme=read('05_assets/body-model-v6/README.md');
const workoutAsset=read('05_assets/workout-benchpress-v1.svg');
const executable=[foundation,screens,runtime].map(stripComments).join('\n');

assert.match(version,/garang-founder-v8-foundation\.css/,'loader must load Founder v8 foundation');
assert.match(version,/garang-founder-v8-screens\.css/,'loader must load Founder v8 screen compositions');
assert.match(version,/garang-founder-v8\.js/,'loader must load Founder v8 structural adapter');
assert.doesNotMatch(version,/garang-founder-exact-v7|garang-founder-target-v6|garang-founder-target-v5|garang-reference-ui-v2|garang-presentation-v4\.(?:css|js)/,'loader must not restore superseded visual layers');
assert.doesNotMatch(executable,/target-board|commercial-approved-v3|reference-board|GARANG_TARGET_UI|\.jpg\b|\.jpeg\b|\.png\b/i,'v8 presentation must not reference target screenshots or cropped concept-board photography');
assert.match(runtime,/workout-benchpress-v1\.svg/,'Workout presentation must use a GARANG-owned original asset');
assert.match(workoutAsset,/GARANG bench press training visual/,'Workout hero asset must be original GARANG SVG');
assert.match(runtime,/body-model-v6\/\$\{gender\}-\$\{bodyView\}\.svg/,'Body must use the dense GARANG-owned mesh visual');
assert.match(bodyReadme,/MakeHuman hm08 basemesh/,'Body mesh provenance must remain documented');
assert.match(bodyReadme,/CC0 1\.0 Universal/,'Body mesh source license must remain documented');
assert.doesNotMatch(runtime,/cloneNode\s*\(/,'presentation must move canonical action/state owners instead of cloning them');
assert.doesNotMatch(runtime,/replaceChildren\s*\(/,'presentation must not replace canonical interactive owners');
assert.match(runtime,/q\(m,'\.gtf-decision'\)/,'Today must reuse canonical decision owner');
assert.match(runtime,/q\(m,'\.gtf-action'\)/,'Today must reuse canonical action owner');
assert.match(screens,/#workoutExecutionRest/,'Rest presentation must style the canonical timer owner');
assert.match(runtime,/['"]\.meal-scan-card['"]/,'Nutrition must reuse canonical Meal Scan owner');
assert.match(runtime,/document\.getElementById\('finishWorkoutSession'\)/,'Record must reuse canonical session finish action');
assert.match(runtime,/q\(m,'\.body-hero-anatomy'\)/,'Body must preserve the canonical muscle interaction owner');
assert.match(screens,/\.g8-body-hit-layer/,'Body canonical hit owner must remain interactive above the visible mesh');
assert.match(foundation,/--g8-bg:#f4f1ec/,'Founder v8 must use the approved light-neutral foundation');
assert.match(foundation,/--g8-red:#e9253d/,'Founder v8 must keep red as restrained accent');
assert.match(foundation,/grid-template-columns:repeat\(4,minmax\(0,1fr\)\)/,'Primary navigation must remain four tabs');
