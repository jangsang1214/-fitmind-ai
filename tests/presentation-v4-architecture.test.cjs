'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=file=>fs.readFileSync(path.join(root,file),'utf8');
const stripComments=value=>String(value).replace(/\/\*[\s\S]*?\*\//g,'').replace(/(^|\s)\/\/.*$/gm,'$1');
const version=read('07_config/version.js');
const css=read('03_styles/runtime/garang-founder-target-v6.css');
const refinement=read('03_styles/runtime/garang-founder-target-v6-refinement.css');
const anatomyCss=read('03_styles/runtime/garang-muscular-anatomy-v1.css');
const runtime=read('06_features/ui/runtime/garang-founder-target-v6.js');
const anatomyRuntime=read('06_features/ui/runtime/garang-muscular-anatomy-v1.js');
const workoutAsset=read('05_assets/workout-benchpress-v1.svg');
const executablePresentation=[css,refinement,anatomyCss,runtime,anatomyRuntime].map(stripComments).join('\n');
const executableRuntime=stripComments(runtime);

assert.match(version,/garang-founder-target-v6\.css/,'version loader must load the clean Founder v6 stylesheet');
assert.match(version,/garang-founder-target-v6\.js/,'version loader must load the clean Founder v6 structural adapter');
assert.match(version,/garang-muscular-anatomy-v1/,'version loader must load the shared GARANG anatomy renderer');
assert.doesNotMatch(version,/garang-founder-target-v5\.(?:css|js)|garang-reference-ui-v2|garang-presentation-v4\.(?:css|js)/,'version loader must not restore superseded presentation layers');
assert.doesNotMatch(executablePresentation,/target-board|commercial-approved-v3|reference-board|\.jpg\b|\.jpeg\b|\.png\b/i,'Founder presentation components must never reference board screenshots or cropped concept photography');
assert.match(runtime,/body-model-v6\/\$\{gender\(\)\}-front\.svg/,'fallback Today anatomy must remain GARANG-owned');
assert.match(runtime,/workout-benchpress-v1\.svg/,'Workout hero must use the original GARANG workout asset');
assert.match(workoutAsset,/GARANG bench press training visual/,'Workout hero asset must be an original GARANG-owned SVG');
assert.match(anatomyRuntime,/Original SVG geometry/,'muscular anatomy must be an authored GARANG renderer');
assert.doesNotMatch(executableRuntime,/cloneNode\s*\(/,'presentation adapter must move canonical owners instead of cloning them');
assert.doesNotMatch(executableRuntime,/replaceChildren\s*\(/,'presentation adapter must not replace canonical interactive geometry');
assert.match(runtime,/qs\(m,'#garangTodayFlow'\)/,'Today must reuse the canonical decision owner');
assert.match(runtime,/document\.getElementById\('workoutExecutionRest'\)/,'Workout Rest must reuse the canonical timer owner');
assert.match(runtime,/qs\(m,'\.meal-scan-card'\)/,'Nutrition must reuse the canonical Meal Scan owner');
assert.match(runtime,/qs\(m,'\.body-hero'\)/,'Body must reuse the canonical body owner');
